// Generate org-prep assets: sObject tree files with a plan, prepare-org.sh and CHECKLIST.md.
import { writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { createResolver, UsageError } from './scenario.mjs';

const MAX_RECORDS_PER_FILE = 200; // sf data import tree limit per file
const ENV_ONLY = /^\{\{\s*env\.([A-Za-z_][A-Za-z0-9_]*)\s*\}\}$/;
const sq = (value) => `'${String(value).replace(/'/g, `'\\''`)}'`;
const isRef = (value) => typeof value === 'string' && value.startsWith('@');

function groupRecords(records) {
  const groups = [];
  const groupOfRef = new Map();
  for (const record of records) {
    let index = groups.findIndex((g) => g.sobject === record.sobject);
    if (index === -1) {
      groups.push({ sobject: record.sobject, records: [] });
      index = groups.length - 1;
    }
    for (const [field, value] of Object.entries(record.fields)) {
      if (!isRef(value)) continue;
      const parent = groupOfRef.get(value.slice(1));
      if (parent === undefined || parent >= index) {
        throw new UsageError(
          `Record "${record.ref}" (${record.sobject}.${field} = ${value}) must point to a record of an sObject imported earlier. ` +
            'Reorder records so every parent sObject appears before its children.',
        );
      }
    }
    groups[index].records.push(record);
    groupOfRef.set(record.ref, index);
  }
  return groups;
}

function userFlag(username) {
  if (!username) return '';
  const env = username.match(ENV_ONLY);
  return env ? ` --on-behalf-of "$${env[1]}"` : ` --on-behalf-of ${sq(username)}`;
}

function buildScript(s, plan, verify) {
  const op = s.orgPrep;
  const L = [
    '#!/usr/bin/env bash',
    `# Generated by presales-demo-scenario-generate from scenario "${s.meta.id}" (version ${s.meta.version ?? 'n/a'}).`,
    '# Do not edit by hand: change the scenario JSON and run org-prep again.',
    '#',
    '# Usage: ./prepare-org.sh [--target-org=<alias>] [--yes] [--reimport]',
    'set -euo pipefail',
    'cd "$(dirname "$0")"',
    '',
    `TARGET_ORG=${sq(op.targetOrg)}`,
    'ASSUME_YES=false',
    'REIMPORT=false',
    'for arg in "$@"; do',
    '  case "$arg" in',
    '    --target-org=*) TARGET_ORG="${arg#*=}" ;;',
    '    --yes) ASSUME_YES=true ;;',
    '    --reimport) REIMPORT=true ;;',
    '    *) echo "Unknown argument: $arg" >&2; exit 2 ;;',
    '  esac',
    'done',
    '',
    '# Safety: only orgs listed in orgPrep.allowedOrgs. Never list a production org there.',
    `ALLOWED_ORGS=(${op.allowedOrgs.map(sq).join(' ')})`,
    'allowed=false',
    'for org in "${ALLOWED_ORGS[@]}"; do',
    '  if [[ "$org" == "$TARGET_ORG" ]]; then allowed=true; fi',
    'done',
    'if [[ "$allowed" != true ]]; then',
    '  echo "Refusing to run: \\"$TARGET_ORG\\" is not in orgPrep.allowedOrgs (${ALLOWED_ORGS[*]})." >&2',
    '  exit 2',
    'fi',
    'command -v sf >/dev/null 2>&1 || { echo "The Salesforce CLI (sf) is not installed." >&2; exit 2; }',
    'command -v node >/dev/null 2>&1 || { echo "node is required to read sf --json output." >&2; exit 2; }',
  ];
  // Fail before touching the org when a persona username is missing.
  // No apostrophes in these messages: bash reads ' inside ${VAR:?...} as a quote even within double quotes.
  const envNames = [
    ...new Set(
      s.personas
        .filter((p) => p.org?.permissionSets?.length)
        .map((p) => p.org.username?.match(ENV_ONLY)?.[1])
        .filter(Boolean),
    ),
  ].sort();
  for (const name of envNames) L.push(`: "\${${name}:?Set ${name} to the username of the persona that uses it}"`);
  L.push(
    '',
    'echo "Target org: $TARGET_ORG"',
    `sf data query --target-org "$TARGET_ORG" --query 'SELECT Name, OrganizationType, IsSandbox FROM Organization'`,
    'if [[ "$ASSUME_YES" != true ]]; then',
    '  read -r -p "Prepare this org for the demo? [y/N] " answer',
    '  [[ "$answer" == "y" || "$answer" == "Y" ]] || { echo "Aborted."; exit 1; }',
    'fi',
  );

  const assignments = s.personas.flatMap((p) => (p.org?.permissionSets ?? []).map((ps) => ({ persona: p, ps })));
  if (assignments.length) {
    L.push('', '# Permission sets per persona (a set that is already assigned only produces a warning)');
    for (const { persona, ps } of assignments) {
      L.push(`echo ${sq(`Assigning ${ps} to ${persona.name}`)}`);
      L.push(
        `sf org assign permset --target-org "$TARGET_ORG" --name ${sq(ps)}${userFlag(persona.org.username)} || ` +
          `echo ${sq(`WARN: could not assign ${ps}; it may be assigned already or missing in the org.`)} >&2`,
      );
    }
  }

  if (op.importRecords && plan.length) {
    L.push(
      '',
      '# Demo records. sf data import tree is not idempotent, so a second import needs --reimport.',
      'if [[ -f import-result.json && "$REIMPORT" != true ]]; then',
      '  echo "Records were imported before (import-result.json exists). Delete them first, or pass --reimport to import duplicates." >&2',
      '  exit 1',
      'fi',
      'if sf data import tree --target-org "$TARGET_ORG" --plan data/plan.json --json > import-result.tmp.json; then',
      '  mv import-result.tmp.json import-result.json',
      '  echo "Records imported. Their IDs are in import-result.json."',
      'else',
      '  echo "Import failed. Details: import-result.tmp.json" >&2',
      '  exit 1',
      'fi',
    );
  }

  if (verify.length) {
    L.push(
      '',
      '# Verification',
      'failures=0',
      'count_rows() {',
      `  sf data query --target-org "$TARGET_ORG" --query "$1" --json | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{console.log(JSON.parse(s).result.totalSize)}catch{console.log(-1)}})'`,
      '}',
      'check() {',
      '  local label="$1" soql="$2" min="$3" n',
      '  n=$(count_rows "$soql") || n=-1',
      '  if (( n >= min )); then',
      '    echo "PASS  $label ($n)"',
      '  else',
      '    echo "FAIL  $label: expected at least $min row(s), got $n" >&2',
      '    failures=$((failures + 1))',
      '  fi',
      '}',
    );
    for (const v of verify) L.push(`check ${sq(v.label)} ${sq(v.soql)} ${v.expectMinRows ?? 1}`);
    L.push('if (( failures > 0 )); then echo "$failures verification(s) failed." >&2; exit 1; fi');
  }
  L.push('', 'echo "Org ready. Next: node scripts/demo.mjs run <scenario.json>"');
  return `${L.join('\n')}\n`;
}

function buildChecklist(s, groups, verify, manualSteps) {
  const op = s.orgPrep;
  const envNames = [
    ...new Set(s.personas.map((p) => p.org?.username?.match(ENV_ONLY)?.[1]).filter(Boolean)),
  ].sort();
  const assignments = s.personas.flatMap((p) => (p.org?.permissionSets ?? []).map((ps) => `${ps} → ${p.name} (${p.role})`));
  const L = [
    `# Org preparation: ${s.meta.title}`,
    '',
    `Target org: \`${op.targetOrg}\` · allowed orgs: ${op.allowedOrgs.map((o) => `\`${o}\``).join(', ')}`,
    '',
    '## 1. Before you run the script',
    '',
    `- [ ] Log the CLI in to the demo org: \`sf org login web --alias ${op.targetOrg}\``,
    '- [ ] Confirm that the org is not production. The script prints OrganizationType and IsSandbox and asks before it changes anything.',
  ];
  if (envNames.length) L.push(`- [ ] Set the persona usernames: ${envNames.map((n) => `\`${n}\``).join(', ')}`);
  if (manualSteps.length) {
    L.push('', '## 2. Manual steps', '');
    for (const step of manualSteps) L.push(`- [ ] ${step}`);
  }
  L.push('', '## 3. Run', '', '```bash', 'bash prepare-org.sh            # asks for confirmation', 'bash prepare-org.sh --yes      # non-interactive', '```');
  L.push('', '## 4. What the script does', '');
  if (assignments.length) L.push(`- Assigns permission sets: ${assignments.join('; ')}`);
  if (op.importRecords && groups.length) {
    const counts = groups.map((g) => `${g.sobject} (${g.records.length})`).join(', ');
    L.push(`- Imports demo records with \`sf data import tree --plan data/plan.json\`: ${counts}`);
  }
  for (const v of verify) L.push(`- Verifies "${v.label}": \`${v.soql}\` returns at least ${v.expectMinRows ?? 1} row(s)`);
  L.push(
    '',
    '## 5. Related sf skills',
    '',
    '- Product catalog (EPC) data: `omnistudio-epc-catalog-generate`',
    '- Larger data volumes and cleanup scripts: `platform-data-manage`',
    '- Queries for checks and reports: `platform-soql-query`',
    '',
    '## 6. After the org is ready',
    '',
    'Run the headless smoke test and fix every failed step: `node scripts/demo.mjs run <scenario.json>`',
  );
  return `${L.join('\n')}\n`;
}

export async function generateOrgPrep(s, outDir) {
  if (!s.orgPrep) throw new UsageError('This scenario has no orgPrep section, so there is nothing to generate.');
  const { resolveDeep, missingEnv } = createResolver(s, { envMode: 'runtime' });
  const records = resolveDeep(s.records);
  const verify = resolveDeep(s.orgPrep.verify);
  const manualSteps = resolveDeep(s.orgPrep.manualSteps);
  if (missingEnv.size) {
    throw new UsageError(`Set these environment variables first (used in records or verify queries): ${[...missingEnv].sort().join(', ')}`);
  }
  const groups = groupRecords(records);

  const dataDir = path.join(outDir, 'data');
  await rm(dataDir, { recursive: true, force: true });
  await mkdir(dataDir, { recursive: true });
  const plan = [];
  let fileNumber = 0;
  for (const group of groups) {
    const files = [];
    for (let i = 0; i < group.records.length; i += MAX_RECORDS_PER_FILE) {
      const chunk = group.records.slice(i, i + MAX_RECORDS_PER_FILE);
      fileNumber += 1;
      const name = `${String(fileNumber).padStart(2, '0')}-${group.sobject}.json`;
      const body = { records: chunk.map((r) => ({ attributes: { type: r.sobject, referenceId: r.ref }, ...r.fields })) };
      await writeFile(path.join(dataDir, name), `${JSON.stringify(body, null, 2)}\n`);
      files.push(name);
    }
    const resolveRefs = group.records.some((r) => Object.values(r.fields).some(isRef));
    plan.push({ sobject: group.sobject, saveRefs: true, resolveRefs, files });
  }
  const written = [];
  if (plan.length) {
    await writeFile(path.join(dataDir, 'plan.json'), `${JSON.stringify(plan, null, 2)}\n`);
    written.push(path.join(dataDir, 'plan.json'), ...plan.flatMap((p) => p.files.map((f) => path.join(dataDir, f))));
  }
  const script = path.join(outDir, 'prepare-org.sh');
  await writeFile(script, buildScript(s, plan, verify), { mode: 0o755 });
  const checklist = path.join(outDir, 'CHECKLIST.md');
  await writeFile(checklist, buildChecklist(s, groups, verify, manualSteps));
  return [script, checklist, ...written];
}
